"""Headless Claude runs. Scheduled tasks and incidents are the ONLY places an LLM is called.

run_task(name, trigger): deterministic code builds a context JSON, checks the daily cap and free RAM
(incident runs skip the RAM gate and may exceed the cap up to 2x), then runs the Claude Code CLI
non-interactively with the prompt from tasks/<name>.md plus the context, a restricted tool list
(rigctl only, wider for incidents), a hard timeout, and RIG_RUN_ID exported so every rigctl action
is tagged with the run. The run is recorded in claude_runs whether it ran, was skipped, or failed.

CLI flags are kept in one place (`cli_args`) because they are the part most likely to need a
touch-up against the installed Claude Code version; `rigctl claude-run --dry` prints the command.
"""
from __future__ import annotations

import json
import logging
import os
import shutil
import subprocess
import time
import uuid as uuidlib
from pathlib import Path
from typing import Any

import psutil

from .config import REPO_ROOT, Config
from .db import Db
from .secrets import get_secret, redact

log = logging.getLogger(__name__)
TASKS_DIR = REPO_ROOT / "tasks"

# Permission rules use the documented "Bash(prefix *)" form (space before *, so "rigctl act *" cannot
# match "rigctl actions"). Needs the Bash tool, i.e. Git for Windows on a Windows hub.
TOOLS = {
    "hourly": ["Bash(rigctl status *)", "Bash(rigctl status)", "Bash(rigctl gpus)", "Bash(rigctl profile show *)",
               "Bash(rigctl trial *)", "Bash(rigctl actions *)", "Bash(rigctl incidents *)", "Bash(rigctl tune *)", "Bash(rigctl tune)"],
    "algo_check": ["Bash(rigctl status)", "Bash(rigctl coins *)", "Bash(rigctl coins)", "Bash(rigctl act switch-coin *)",
                   "Bash(rigctl pool *)", "Bash(rigctl pool)", "WebFetch", "WebSearch"],
    "incident": ["Bash(rigctl *)", "Bash(nvidia-smi *)", "Bash(nvidia-smi)", "Bash(sc *)", "Bash(tasklist *)", "Bash(systemctl *)",
                 "Bash(journalctl *)", "Bash(powershell *)", "Bash(Get-WinEvent *)", "Read", "Grep", "Glob", "WebFetch", "WebSearch"],
}


class ClaudeRunner:
    def __init__(self, cfg: Config, db: Db, clock=time.time, runner=None):
        self.cfg, self.db, self.clock = cfg, db, clock
        self.c = cfg.get("claude", {}) or {}
        self.runner = runner or self._subprocess          # injectable for tests

    # --- gates ---------------------------------------------------------------------------------------
    def runs_today(self) -> int:
        day = time.strftime("%Y-%m-%d", time.localtime(self.clock()))
        return self.db.one("SELECT COUNT(*) c FROM claude_runs WHERE status IN ('ok','error','timeout') AND date(started,'unixepoch','localtime')=?",
                           (day,))["c"]

    def gate(self, task: str, trigger: str) -> str | None:
        cap = int(self.c.get("daily_cap", 10))
        n = self.runs_today()
        incident = task == "incident"
        if n >= (cap * 2 if incident else cap):
            return f"daily cap reached ({n}/{cap}{' x2 for incidents' if incident else ''})"
        if not incident:
            free_mb = psutil.virtual_memory().available / 2**20
            if free_mb < float(self.c.get("min_free_ram_mb", 1500)):
                return f"free RAM {free_mb:.0f} MB below {self.c.get('min_free_ram_mb', 1500)} MB"
        if not shutil.which(str(self.c.get("bin", "claude"))):
            return f"claude CLI not found: {self.c.get('bin', 'claude')}"
        if not (get_secret("CLAUDE_CODE_OAUTH_TOKEN") or get_secret("ANTHROPIC_API_KEY")):
            return "no CLAUDE_CODE_OAUTH_TOKEN (claude setup-token) or ANTHROPIC_API_KEY in secrets"
        return None

    # --- prompt --------------------------------------------------------------------------------------
    def prompt(self, task: str, context: dict) -> str:
        body = (TASKS_DIR / f"{task}.md").read_text(encoding="utf-8")
        ctx = json.dumps(context, indent=1, default=str)
        return f"{body}\n\n## Context (generated by rig-overseer at {time.strftime('%Y-%m-%d %H:%M %Z')})\n```json\n{ctx}\n```\n"

    def cli_args(self, task: str, run_id: str) -> list[str]:
        args = [str(self.c.get("bin", "claude")), "-p", "--output-format", "json", "--no-session-persistence",
                "--max-turns", str(self.c.get("max_turns", 25)),
                "--allowedTools", ",".join(TOOLS.get(task, TOOLS["hourly"])),
                "--disallowedTools", "Edit,Write,NotebookEdit,MultiEdit" if task != "incident" else "NotebookEdit",
                "--append-system-prompt", f"You are rig-overseer's {task} task (run {run_id}). Hardware and miner changes only "
                                          f"through the allowed rigctl commands; keep the final answer under 300 words."]
        if self.c.get("model"):
            args += ["--model", str(self.c["model"])]
        # an API key is billed per call: cap it. Subscription tokens have no per-run cost to cap.
        if get_secret("ANTHROPIC_API_KEY") and not get_secret("CLAUDE_CODE_OAUTH_TOKEN") and self.c.get("max_budget_usd"):
            args += ["--max-budget-usd", str(self.c["max_budget_usd"])]
        return args

    def _subprocess(self, args: list[str], prompt: str, env: dict, timeout: float) -> dict:
        p = subprocess.run(args, input=prompt, capture_output=True, text=True, env=env, timeout=timeout, cwd=str(REPO_ROOT))
        return {"rc": p.returncode, "stdout": p.stdout, "stderr": p.stderr}

    # --- run -------------------------------------------------------------------------------------------
    def run_task(self, task: str, trigger: str, context: dict, *, schedule: str | None = None, dry: bool = False) -> dict:
        run_id = f"{task}-{time.strftime('%Y%m%d-%H%M', time.localtime(self.clock()))}-{uuidlib.uuid4().hex[:4]}"
        started = self.clock()
        if task not in TOOLS or not (TASKS_DIR / f"{task}.md").is_file():
            raise ValueError(f"unknown task {task!r}")
        if dry:
            return {"run_id": run_id, "args": self.cli_args(task, run_id), "prompt": self.prompt(task, context)}
        self.db.execute("INSERT INTO claude_runs(run_id, task, trigger, schedule, started, status) VALUES(?,?,?,?,?,'running')",
                        (run_id, task, trigger, schedule, started))
        reason = self.gate(task, trigger)
        if reason:
            self._close(run_id, "skipped", summary=f"skipped: {reason}", output="")
            log.info("claude %s skipped: %s", task, reason)
            return {"run_id": run_id, "status": "skipped", "summary": reason}
        env = dict(os.environ)
        env["RIG_RUN_ID"] = run_id
        env["RIG_CONFIG"] = env.get("RIG_CONFIG", "")
        tok = get_secret("CLAUDE_CODE_OAUTH_TOKEN")
        if tok:
            env["CLAUDE_CODE_OAUTH_TOKEN"] = tok
        key = get_secret("ANTHROPIC_API_KEY")
        if key and not tok:
            env["ANTHROPIC_API_KEY"] = key
        env.setdefault("CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC", "1")
        prompt = self.prompt(task, context)
        try:
            res = self.runner(self.cli_args(task, run_id), prompt, env, float(self.c.get("timeout_s", 900)))
        except subprocess.TimeoutExpired:
            self._close(run_id, "timeout", summary="timed out", output="")
            return {"run_id": run_id, "status": "timeout"}
        except Exception as e:
            self._close(run_id, "error", summary=f"launch failed: {e}"[:300], output="")
            return {"run_id": run_id, "status": "error", "summary": str(e)}
        parsed = self._parse(res.get("stdout", ""))
        status = "ok" if res.get("rc", 1) == 0 and not parsed.get("is_error") else "error"
        text = parsed.get("result") or res.get("stdout", "")
        summary = (text.strip().splitlines() or [""])[0][:300] if text else (res.get("stderr") or "")[:300]
        usage = parsed.get("usage") or {}
        out = redact(f"{text}\n\n--- stderr ---\n{res.get('stderr', '')}" if res.get("stderr") else text)
        actions = [dict(r) for r in self.db.query("SELECT ts, gpu_id, action, params, before, after, ok, dry_run FROM actions WHERE run_id=?", (run_id,))]
        self._close(run_id, status, summary=redact(summary), output=out, cost=parsed.get("total_cost_usd"),
                    tokens_in=usage.get("input_tokens"), tokens_out=usage.get("output_tokens"), actions=actions)
        log.info("claude %s %s: %s", task, status, summary)
        return {"run_id": run_id, "status": status, "summary": summary, "cost_usd": parsed.get("total_cost_usd"), "actions": len(actions)}

    @staticmethod
    def _parse(stdout: str) -> dict:
        s = stdout.strip()
        if not s:
            return {}
        try:
            d = json.loads(s)
            return d if isinstance(d, dict) else {"result": s}
        except ValueError:
            for line in reversed(s.splitlines()):           # stream-json: last object with a result
                try:
                    d = json.loads(line)
                    if isinstance(d, dict) and "result" in d:
                        return d
                except ValueError:
                    continue
            return {"result": s}

    def _close(self, run_id: str, status: str, *, summary: str, output: str, cost: float | None = None,
               tokens_in: int | None = None, tokens_out: int | None = None, actions: list | None = None) -> None:
        self.db.execute("UPDATE claude_runs SET ended=?, status=?, summary=?, output=?, cost_usd=?, tokens_in=?, tokens_out=?, "
                        "actions_json=? WHERE run_id=?",
                        (self.clock(), status, summary, output, cost, tokens_in, tokens_out,
                         json.dumps(actions, default=str) if actions is not None else None, run_id))
